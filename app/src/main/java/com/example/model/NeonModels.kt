enum class FrameAspectRatio(
    val id: String,
    val label: String,
    val ratio: Float,
    val fullHdWidth: Int,
    val fullHdHeight: Int,
    val uhd4kWidth: Int,
    val uhd4kHeight: Int,
    val masterWidth: Int,
    val masterHeight: Int
) {
    SQUARE_1_1("1:1", "Square 1:1", 1f, 1080, 1080, 2160, 2160, 15360, 15360),
    LANDSCAPE_16_9("16:9", "Landscape 16:9", 16f / 9f, 1920, 1080, 3840, 2160, 15360, 8640),
    PORTRAIT_9_16("9:16", "Portrait 9:16", 9f / 16f, 1080, 1920, 2160, 3840, 8640, 15360);

    fun widthForTier(tier: ExportResolutionTier): Int = when (tier) {
        ExportResolutionTier.FULL_HD -> fullHdWidth
        ExportResolutionTier.UHD_4K -> uhd4kWidth
        ExportResolutionTier.MASTER_16K_TILED -> masterWidth
    }

    fun heightForTier(tier: ExportResolutionTier): Int = when (tier) {
        ExportResolutionTier.FULL_HD -> fullHdHeight
        ExportResolutionTier.UHD_4K -> uhd4kHeight
        ExportResolutionTier.MASTER_16K_TILED -> masterHeight
    }
}

